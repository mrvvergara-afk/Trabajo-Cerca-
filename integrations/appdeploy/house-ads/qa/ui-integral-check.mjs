import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {existsSync, mkdirSync, writeFileSync} from 'node:fs';

mkdirSync('qa-output/ui-integral', {recursive:true});
const browser = await chromium.launch({headless:true, ...(existsSync('/usr/bin/google-chrome') ? {executablePath:'/usr/bin/google-chrome'} : {})});
const result = {rendering:'actual React candidate, isolated SDK adapter', productionWrites:0, radar:{}, catalog503:{}};
try {
  const context = await browser.newContext({viewport:{width:390,height:844}, reducedMotion:'no-preference'});
  const page = await context.newPage();
  await page.addInitScript(() => { window.houseFixture = 'territory'; });
  await page.goto('http://127.0.0.1:4174/', {waitUntil:'networkidle'});
  await page.waitForFunction(() => document.querySelector('#neo-jobs')?.getAttribute('aria-busy') === 'false');
  const radar = page.locator('#neo-radar');
  await radar.locator('summary').click();
  await radar.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#neo-radar')?.getAttribute('data-rotating') === 'true');
  const first = await radar.getAttribute('data-focus-town');
  const countBefore = await page.evaluate(() => window.houseCalls.filter(c => c.path.startsWith('/api/listings')).length);
  await page.waitForFunction(town => document.querySelector('#neo-radar')?.getAttribute('data-focus-town') !== town, first, {timeout:5500});
  const second = await radar.getAttribute('data-focus-town');
  assert.notEqual(first, second);
  assert.equal(await page.evaluate(() => window.houseCalls.filter(c => c.path.startsWith('/api/listings')).length), countBefore);
  await page.screenshot({path:'qa-output/ui-integral/radar-390.png'});
  await page.evaluate(() => scrollTo(0,0));
  await page.waitForFunction(() => document.querySelector('#neo-radar')?.getAttribute('data-rotating') === 'false');
  const offscreenTown = await radar.getAttribute('data-focus-town');
  await page.waitForTimeout(3200);
  assert.equal(await radar.getAttribute('data-focus-town'), offscreenTown);
  await radar.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#neo-radar')?.getAttribute('data-rotating') === 'true');
  // Exercise the browser visibility event in the isolated test, without claiming physical device background delivery.
  await page.evaluate(() => { Object.defineProperty(document,'visibilityState',{configurable:true,value:'hidden'}); document.dispatchEvent(new Event('visibilitychange')); });
  await page.waitForFunction(() => document.querySelector('#neo-radar')?.getAttribute('data-rotating') === 'false');
  const hiddenTown = await radar.getAttribute('data-focus-town');
  await page.waitForTimeout(3200);
  assert.equal(await radar.getAttribute('data-focus-town'), hiddenTown);
  await page.evaluate(() => { Object.defineProperty(document,'visibilityState',{configurable:true,value:'visible'}); document.dispatchEvent(new Event('visibilitychange')); });
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(() => document.querySelector('#neo-radar')?.getAttribute('data-rotating') === 'false');
  assert.equal(await radar.locator('.tcRadarSweep').evaluate(e => getComputedStyle(e).animationName), 'none');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await radar.getByRole('button', {name:'Lumaco 12 ofertas',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#tc-results-title')?.textContent.includes('Lumaco'));
  assert.equal(await radar.getAttribute('data-focus-town'),'Lumaco');
  await radar.scrollIntoViewIfNeeded();
  await page.waitForTimeout(3200);
  assert.equal(await radar.getAttribute('data-rotating'),'false');
  assert.equal(await radar.getAttribute('data-focus-town'),'Lumaco');
  result.radar = {first,second,all13ManualTowns:await radar.locator('.tcRadarTowns button').count(),periodMs:3000,noExtraCatalogCalls:true,offscreenPaused:true,visibilityEventPaused:true,reducedMotionPaused:true,manualSelectionPaused:true,resultsTown:'Lumaco'};
  await context.close();
  const faultContext = await browser.newContext({viewport:{width:390,height:844}});
  const fault = await faultContext.newPage();
  await fault.addInitScript(() => { window.houseFixture = 'catalog-503'; });
  await fault.goto('http://127.0.0.1:4174/', {waitUntil:'networkidle'});
  await fault.getByRole('button', {name:/Reintentar/}).first().waitFor();
  assert.equal(await fault.locator('.neoJobCard').count(),0);
  const text = await fault.locator('#neo-jobs').innerText();
  assert(/No pudimos|error|recuperar|disponible|cargar/i.test(text));
  await fault.screenshot({path:'qa-output/ui-integral/catalog-503-isolated.png',fullPage:true});
  result.catalog503 = {isolatedFault:true,visibleErrorAndRetry:true,noFabricatedCards:true};
  await faultContext.close();
  writeFileSync('qa-output/ui-integral/checks.json',JSON.stringify(result,null,2));
  console.log('UI_INTEGRAL_PROOF '+JSON.stringify(result));
} finally { await browser.close(); }
